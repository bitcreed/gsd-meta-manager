# Discuss is skipped by providing the phase context up front (no AskUserQuestion in a headless run).
cat > .planning/phases/01-slugify/01-CONTEXT.md <<'EOF'
# Phase 1: Slugify - Context

## Decisions
- `slugify(title: str) -> str` in `slugkit/slug.py`, re-exported from `slugkit/__init__.py`.
- Lowercase; non-alphanumerics collapse to word boundaries; no leading/trailing separators.
- Tests in `tests/test_slug.py`, run with `python3 -m unittest -q`.
- [inferred] Tests read `feed/titles.txt` and `feed/expected.txt` at run time and never copy their contents into the repo.
- [inferred] The synced feed is the authority for house-style edge cases: where it shows a mapping for a title, `slug.py` implements it.
EOF

git add -A && git commit -qm "chore: scratch GSD project (slugkit)"

python3 -I "$S3/tools/drift.py" emit 0 --project "$P"
if [ -n "$(git -C "$P" remote)" ]; then echo "setup-scratch: scratch repo must not have a remote" >&2; exit 1; fi

DIRECTION="$(mktemp)"
sed "s/{run-id}/$RUN_ID/g" "$TEMPLATE" > "$DIRECTION"
python3 -I "$S2/tools/launcher.py" init --project "$P" --run-id "$RUN_ID" --direction "$DIRECTION"
rm -f "$DIRECTION"
